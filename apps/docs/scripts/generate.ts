/** Splits Markdown into the text before the first `## ` heading and one entry per `## ` section. */
export function splitSections(markdown: string): { intro: string; sections: Section[] } {
  const [head = "", ...rest] = markdown.split(/^## /m);
  return {
    intro: head.replace(/^# .*\n/, "").trim(),
    sections: rest.map((part) => {
      const newline = part.indexOf("\n");
      if (newline === -1) return { title: part.trim(), body: "" };
      return { title: part.slice(0, newline).trim(), body: part.slice(newline + 1).trim() };
    }),
  };
}

/** Promotes a single extracted section so its `###` headings become `##`. */
export const promoteHeadings = (body: string): string => body.replace(/^###/gm, "##");

const joinSections = (parts: readonly Section[]): string =>
  parts.map((section) => `## ${section.title}\n\n${section.body}`).join("\n\n");

