/** Resolves a path relative to a source directory (e.g. `docs/`) into a repo-relative POSIX path. */
function resolveRepoPath(sourceFile: string, targetPath: string): string {
  const baseParts = sourceFile.split("/").slice(0, -1);
  for (const segment of targetPath.split("/")) {
    if (!segment || segment === ".") continue;
    if (segment === "..") baseParts.pop();
    else baseParts.push(segment);
  }
  return baseParts.join("/");
}

/**
 * Rewrites relative Markdown links outside fenced code blocks:
 * - links to mapped docs pages become site-root routes (`/guides/editing/#takes`)
 * - links to repo-only artifacts (`docs/plans/*`, `docs/measurements/*`, `README.md`) become
 *   GitHub links under `REPO`
 * Throws if any relative `.md` or `.json` link cannot be mapped.
 */
export function rewriteDocLinks(
  markdown: string,
  sourceFile: string,
  extraRules: readonly [RegExp, string][] = [],
): string {
  let fence: string | null = null;
  const lines = markdown.split("\n").map((line) => {
    const open = /^\s*(`{3,}|~{3,})/.exec(line);
    if (fence) {
      if (open && open[1] && open[1][0] === fence[0] && open[1].length >= fence.length) {
        fence = null;
      }
      return line;
    }
    if (open && open[1]) {
      fence = open[1];
      return line;
    }
    let updated = line.replace(
      /\]\(([^)\s]+)(?:\s+"([^"]*)")?\)/g,
      (match, rawTarget: string, title?: string) => {
        if (
          rawTarget.startsWith("#") ||
          rawTarget.startsWith("/") ||
          /^[a-z][a-z\d+.-]*:/i.test(rawTarget)
        ) {
          return match;
        }
        const hashIndex = rawTarget.indexOf("#");
        const pathPart = hashIndex === -1 ? rawTarget : rawTarget.slice(0, hashIndex);
        const hashPart = hashIndex === -1 ? "" : rawTarget.slice(hashIndex);
        const repoPath = resolveRepoPath(sourceFile, pathPart);
        const route = DOC_ROUTES.get(repoPath);
        const suffix = title ? ` "${title}"` : "";
        if (route) return `](${route}${hashPart}${suffix})`;
        if (
          repoPath.startsWith("docs/plans/") ||
          repoPath.startsWith("docs/measurements/") ||
          repoPath === "README.md"
        ) {
          return `](${REPO}/${repoPath}${hashPart}${suffix})`;
        }
        throw new Error(`${sourceFile}: unmapped relative link "${rawTarget}" (${repoPath})`);
      },
    );
    for (const [pattern, replacement] of extraRules) {
      updated = updated.replace(pattern, replacement);
    }
    return updated;
  });
  return lines.join("\n");
}

/** The tabs of every framework example group, in order. */
export const FRAMEWORK_TABS: readonly string[] = ["Vanilla", "React", "Svelte", "SolidJS", "Vue"];

const TABS_OPEN = "<!-- framework-tabs -->";
const TABS_CLOSE = "<!-- /framework-tabs -->";

/** The MDX import that `frameworkTabs` output needs. */
export const TABS_IMPORT = 'import { TabItem, Tabs } from "@astrojs/starlight/components";';

/**
 * Turns each framework example group into Starlight tabs that share one choice across the site.
 * In the repository's Markdown a group reads as labelled code blocks:
 *
 *     <!-- framework-tabs -->
 *     **Vanilla**
 *     ```js
 *     …
 *     ```
 *     **React**
 *     …
 *     <!-- /framework-tabs -->
 *
 * Each label in `FRAMEWORK_TABS` must appear once, in order, followed by one fenced block.
 * Throws on anything else, so a group cannot lose a framework without failing the build.
 */
export function frameworkTabs(markdown: string, sourceFile: string): string {
  const lines = markdown.split("\n");
  const out: string[] = [];
  let index = 0;
  while (index < lines.length) {
    const line = lines[index] ?? "";
    if (line.trim() === TABS_CLOSE) {
      throw new Error(`${sourceFile}: ${TABS_CLOSE} without ${TABS_OPEN}`);
    }
    if (line.trim() !== TABS_OPEN) {
      out.push(line);
      index++;
      continue;
    }
    index++;
    const tabs: { label: string; code: string[] }[] = [];
    let closed = false;
    while (index < lines.length) {
      const current = (lines[index] ?? "").trim();
      index++;
      if (current === "") continue;
      if (current === TABS_CLOSE) {
        closed = true;
        break;
      }
      const label = /^\*\*(.+)\*\*$/.exec(current)?.[1];
      if (!label) {
        throw new Error(
          `${sourceFile}: expected a **Label** line in a framework group: ${current}`,
        );
      }
      while ((lines[index] ?? "").trim() === "") index++;
      const fence = /^(`{3,}|~{3,})/.exec(lines[index] ?? "")?.[1];
      if (!fence) throw new Error(`${sourceFile}: **${label}** is not followed by a code block`);
      const code = [lines[index] ?? ""];
      index++;
      while (index < lines.length) {
        const body = lines[index] ?? "";
        code.push(body);
        index++;
        const close = /^\s*(`{3,}|~{3,})\s*$/.exec(body)?.[1];
        if (close && close[0] === fence[0] && close.length >= fence.length) break;
      }
      tabs.push({ label, code });
    }
    const labels = tabs.map((tab) => tab.label);
    if (!closed || labels.join() !== FRAMEWORK_TABS.join()) {
      throw new Error(
        `${sourceFile}: a framework group needs the tabs ${FRAMEWORK_TABS.join(", ")} in order and ${TABS_CLOSE}; found ${labels.join(", ") || "none"}`,
      );
    }
    out.push('<Tabs syncKey="framework">');
    for (const tab of tabs) {
      out.push(`<TabItem label="${tab.label}">`, "", ...tab.code, "", "</TabItem>");
    }
    out.push("</Tabs>");
  }
  return out.join("\n");
}

