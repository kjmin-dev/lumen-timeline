async function writePage(
  relativePath: string,
  frontmatter: { title: string; description: string; order: number; badge?: string },
  body: string,
): Promise<void> {
  const file = join(content, relativePath);
  await mkdir(join(file, ".."), { recursive: true });
  const lines = [
    `title: ${JSON.stringify(frontmatter.title)}`,
    `description: ${JSON.stringify(frontmatter.description)}`,
    "sidebar:",
    `  order: ${frontmatter.order}`,
  ];
  if (frontmatter.badge) {
    lines.push(`  badge:\n    text: ${JSON.stringify(frontmatter.badge)}\n    variant: note`);
  }
  await writeFile(file, `---\n${lines.join("\n")}\n---\n\n${body.trim()}\n`);
}

function stripTitle(markdown: string): string {
  return markdown.replace(/^# .*\n+/, "").trim();
}

async function copyDoc(
  sourceFile: string,
  outPath: string,
  meta: { title: string; description: string; order: number; badge?: string },
  options: {
    prefix?: string;
    transform?: (body: string) => string;
    extraRules?: readonly [RegExp, string][];
    mdx?: boolean;
  } = {},
): Promise<void> {
  const raw = await readFile(join(root, sourceFile), "utf8");
  let body = rewriteDocLinks(stripTitle(raw), sourceFile, options.extraRules);
  if (options.transform) body = options.transform(body);
  const tabbed = frameworkTabs(body, sourceFile);
  if (tabbed !== body && !options.mdx) {
    throw new Error(`${sourceFile}: framework tabs need an .mdx page; pass mdx: true`);
  }
  body = tabbed;
  const note = options.mdx ? NOTE(sourceFile) : HTML_NOTE(sourceFile);
  const imports = tabbed.includes('<Tabs syncKey="framework">') ? [TABS_IMPORT] : [];
  const parts = [note, ...imports, ...(options.prefix ? [options.prefix] : []), body];
  await writePage(outPath, meta, parts.join("\n\n"));
}

