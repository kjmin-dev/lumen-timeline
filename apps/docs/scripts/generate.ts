function table(header: readonly string[], rows: readonly (readonly string[])[]): string {
  return [
    `| ${header.join(" | ")} |`,
    `| ${header.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.join(" | ")} |`),
  ].join("\n");
}

function readObj(value: unknown, label: string): Record<string, unknown> {
  if (!isRecord(value)) throw new Error(`Expected object at ${label}`);
  return value;
}

function readNum(obj: Record<string, unknown>, key: string, label: string): number {
  const value = obj[key];
  if (typeof value !== "number") throw new Error(`Expected number at ${label}.${key}`);
  return value;
}

function readStr(obj: Record<string, unknown>, key: string, label: string): string {
  const value = obj[key];
  if (typeof value !== "string") throw new Error(`Expected string at ${label}.${key}`);
  return value;
}

const ms = (value: number, digits = 2): string => `${value.toFixed(digits)} ms`;
const mib = (bytes: number): string =>
  bytes === 0 ? "0" : `${(bytes / (1024 * 1024)).toFixed(1)} MiB`;

async function generateMeasurements(): Promise<void> {
  const readJson = async (name: string): Promise<Record<string, unknown>> =>
    readObj(
      JSON.parse(await readFile(join(root, "docs/measurements", name), "utf8")),
      `docs/measurements/${name}`,
    );

  const render = await readJson("render.json");
  const wrappers = await readJson("wrappers.json");
  const peaks = await readJson("peaks.json");
  const commit = await readJson("commit.json");
  const session = await readJson("session.json");

  // 1. Rendering benchmark
  const renderMachine = readObj(render["machine"], "render.machine");
  const renderBrowser = readObj(render["browser"], "render.browser");
  const renderBackends = readObj(render["backends"], "render.backends");
  const renderRows: string[][] = [];
  for (const [key, label] of [
    ["webgl2", "WebGL2"],
    ["webgpu", "WebGPU"],
    ["canvas2d", "Canvas 2D"],
  ] as const) {
    const entry = readObj(renderBackends[key], `render.backends.${key}`);
    const trace = readObj(entry["trace"], `${key}.trace`);
    const work = readObj(trace["work"], `${key}.trace.work`);
    const seeks = readObj(entry["seeks"], `${key}.seeks`);
    const cold = readObj(seeks["cold"], `${key}.seeks.cold`);
    const warm = readObj(seeks["warm"], `${key}.seeks.warm`);
    const coldBuilt = readObj(cold["built"], `${key}.cold.built`);
    const coldDrawn = readObj(cold["drawn"], `${key}.cold.drawn`);
    const warmBuilt = readObj(warm["built"], `${key}.warm.built`);
    const warmDrawn = readObj(warm["drawn"], `${key}.warm.drawn`);
    const memory = readObj(entry["memory"], `${key}.memory`);
    renderRows.push([
      label,
      `${readNum(work, "p50", "work").toFixed(1)} / ${readNum(work, "p95", "work").toFixed(1)} / ${readNum(work, "p99", "work").toFixed(1)} ms`,
      `${(readNum(trace, "missedShare", "trace") * 100).toFixed(2)}%`,
      `${Math.round(readNum(coldBuilt, "p50", "coldBuilt"))} / ${Math.round(readNum(coldDrawn, "p50", "coldDrawn"))} ms`,
      `${Math.round(readNum(warmBuilt, "p50", "warmBuilt"))} / ${Math.round(readNum(warmDrawn, "p50", "warmDrawn"))} ms`,
      mib(readNum(memory, "jsHeap", "memory")),
      mib(readNum(memory, "tiles", "memory")),
      mib(readNum(memory, "gpu", "memory")),
    ]);
  }

  // 2. Framework wrappers benchmark
  const wrapMachine = readObj(wrappers["machine"], "wrappers.machine");
  const wrapBrowser = readObj(wrappers["browser"], "wrappers.browser");
  const wrapSummary = readObj(wrappers["summary"], "wrappers.summary");
  const wrapRows: string[][] = [];
  for (const [key, label] of [
    ["vanilla", "Vanilla"],
    ["react", "React"],
    ["svelte", "Svelte"],
    ["solid", "SolidJS"],
    ["vue", "Vue"],
  ] as const) {
    const row = readObj(wrapSummary[key], `wrappers.summary.${key}`);
    const missedPct = readNum(row, "missedShare", key) * 100;
    const missedSpread = readNum(row, "missedShareSpread", key) * 100;
    wrapRows.push([
      label,
      ms(readNum(row, "workP50", key), 1),
      `${readNum(row, "workP95", key).toFixed(1)} ± ${readNum(row, "workP95Spread", key).toFixed(1)} ms`,
      `${readNum(row, "inputP95", key).toFixed(1)} ± ${readNum(row, "inputP95Spread", key).toFixed(1)} ms`,
      missedSpread > 0
        ? `${missedPct.toFixed(2)} ± ${missedSpread.toFixed(2)}%`
        : `${missedPct.toFixed(2)}%`,
    ]);
  }

  // 3. Peak tile worker benchmark
  const peaksMachine = readObj(peaks["machine"], "peaks.machine");
  const peaksEngines = readObj(peaks["engines"], "peaks.engines");
  const peakRows: string[][] = [];
  for (const [key, label] of [
    ["chromium", "Chrome"],
    ["firefox", "Firefox"],
    ["webkit", "WebKit"],
  ] as const) {
    const eng = readObj(peaksEngines[key], `peaks.engines.${key}`);
    const version = readStr(eng, "version", key);
    const worker = readObj(eng["worker"], `${key}.worker`);
    const cellFor = (size: string): string => {
      const bucket = readObj(worker[size], `${key}.worker.${size}`);
      const jsP50 = readNum(readObj(bucket["js"], "js"), "p50", "js");
      const wasmP50 = readNum(readObj(bucket["current"], "current"), "p50", "current");
      return `${jsP50.toFixed(3)} / ${wasmP50.toFixed(3)} ms`;
    };
    peakRows.push([
      `${label} ${version}`,
      cellFor("4096"),
      cellFor("65536"),
      cellFor("262144"),
      cellFor("1048576"),
    ]);
  }

  // 4. Core commit latency
  const commitMachine = readObj(commit["machine"], "commit.machine");
  const commitOps = readObj(commit["commits"], "commit.commits");
  const commitRows = Object.entries(commitOps).map(([name, val]) => {
    const stat = readObj(val, `commit.${name}`);
    return [name, ms(readNum(stat, "p50", name)), ms(readNum(stat, "p95", name))];
  });

  // 5. Shared session / replace latency
  const sessionMachine = readObj(session["machine"], "session.machine");
  const sessionOps = readObj(session["milliseconds"], "session.milliseconds");
  const sessionRows = Object.entries(sessionOps).map(([name, val]) => {
    const stat = readObj(val, `session.${name}`);
    return [name, ms(readNum(stat, "p50", name)), ms(readNum(stat, "p95", name))];
  });

  const body = [
    HTML_NOTE("docs/measurements/*.json"),
    "Every table below is generated directly from the committed JSON records in [`docs/measurements/`](" +
      `${REPO}/docs/measurements` +
      "). Reproduce them locally with the `npm run bench:*` scripts.",
    "## 20,000-clip rendering trace",
    `Recorded ${readStr(render, "recorded", "render").slice(0, 10)} on ${readStr(renderMachine, "cpu", "render.machine")} (${readStr(renderBrowser, "name", "render.browser")} ${readStr(renderBrowser, "version", "render.browser")}). 60-second pan, zoom and drag trace over 40 tracks, 20,000 clips, 1080p video and eight audio sources. [Raw JSON](${REPO}/docs/measurements/render.json)`,
    table(
      [
        "Backend",
        "Frame work p50 / p95 / p99",
        "Missed refreshes",
        "Cold seek: built / drawn",
        "Warm seek: built / drawn",
        "JS heap",
        "Tiles",
        "GPU",
      ],
      renderRows,
    ),
    "## Framework wrappers vs. vanilla",
    `Recorded ${readStr(wrappers, "recorded", "wrappers").slice(0, 10)} on ${readStr(wrapMachine, "cpu", "wrappers.machine")} (${readStr(wrapBrowser, "name", "wrappers.browser")} ${readStr(wrapBrowser, "version", "wrappers.browser")}), five production runs over WebGL2. [Raw JSON](${REPO}/docs/measurements/wrappers.json)`,
    table(
      [
        "Consumer",
        "Frame work p50",
        "Frame work p95",
        "Pointer to frame end p95",
        "Missed refreshes",
      ],
      wrapRows,
    ),
    "## Waveform peak worker (JS / Rust SIMD)",
    `Recorded ${readStr(peaks, "recorded", "peaks").slice(0, 10)} on ${readStr(peaksMachine, "cpu", "peaks.machine")}. Median full worker round trips per sample batch size. [Raw JSON](${REPO}/docs/measurements/peaks.json)`,
    table(
      ["Engine", "4,096 samples", "65,536 samples", "262,144 samples", "1,048,576 samples"],
      peakRows,
    ),
    "## Core commit latency (20,000 clips)",
    `Recorded ${readStr(commit, "recorded", "commit").slice(0, 10)} on ${readStr(commitMachine, "cpu", "commit.machine")} (Node ${readStr(commit, "node", "commit")}). Commit plus first view read on a 40-track, 20,000-clip, 2,000-marker project. [Raw JSON](${REPO}/docs/measurements/commit.json)`,
    table(["Operation", "p50", "p95"], commitRows),
    "## Snapshot adoption and shared sessions (20,000 clips)",
    `Recorded ${readStr(session, "recorded", "session").slice(0, 10)} on ${readStr(sessionMachine, "cpu", "session.machine")} (Node ${readStr(session, "node", "session")}). [Raw JSON](${REPO}/docs/measurements/session.json)`,
    table(["Operation", "p50", "p95"], sessionRows),
  ].join("\n\n");

  await writePage(
    "benchmarks/measurements.md",
    {
      title: "Recorded measurements",
      description:
        "Machine-readable benchmark results from docs/measurements/ for rendering, wrappers, waveform tiles, core commits and shared sessions.",
      order: 2,
    },
    body,
  );
}

