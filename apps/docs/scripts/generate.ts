function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/** Extracts top-level exported value and type names from a package's committed `api/index.d.ts`. */
export function parseApiExports(dts: string): { values: string[]; types: string[] } {
  const values = new Set<string>();
  const types = new Set<string>();
  const lines = dts.split("\n");
  for (const line of lines) {
    const trimmed = line.trim();
    const namedType = /^export\s+type\s+\{([^}]+)\}/.exec(trimmed);
    if (namedType && namedType[1]) {
      for (const item of namedType[1].split(",")) {
        const name = item
          .trim()
          .split(/\s+as\s+/)
          .at(-1)
          ?.trim();
        if (name) types.add(name);
      }
      continue;
    }
    const namedValue = /^export\s+\{([^}]+)\}/.exec(trimmed);
    if (namedValue && namedValue[1]) {
      for (const item of namedValue[1].split(",")) {
        const cleaned = item.trim();
        if (!cleaned) continue;
        if (cleaned.startsWith("type ")) {
          const name = cleaned
            .slice(5)
            .split(/\s+as\s+/)
            .at(-1)
            ?.trim();
          if (name) types.add(name);
        } else {
          const name = cleaned
            .split(/\s+as\s+/)
            .at(-1)
            ?.trim();
          if (name) values.add(name);
        }
      }
      continue;
    }
    const declValue = /^export\s+declare\s+(?:function|const|class)\s+(\w+)/.exec(trimmed);
    if (declValue && declValue[1]) {
      values.add(declValue[1]);
      continue;
    }
    const declType = /^export\s+(?:interface|type)\s+(\w+)/.exec(trimmed);
    if (declType && declType[1]) {
      types.add(declType[1]);
    }
  }
  return { values: [...values], types: [...types] };
}

