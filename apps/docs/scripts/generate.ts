async function generateFrameworks(): Promise<void> {
  const source = "docs/frameworks.md";
  const raw = rewriteDocLinks(await readFile(join(root, source), "utf8"), source);
  const parsed = splitSections(raw);
  const used = new Set<string>();

  const plan: readonly FrameworkPlan[] = [
    {
      path: "overview",
      title: "Overview & contract",
      description:
        "How the React, Svelte, SolidJS and Vue wrappers mount one shared timeline view and select editor and transport fields.",
      take: [],
      intro: true,
    },
    {
      path: "react",
      title: "React",
      description: "Mount Lumen Timeline in React 19 with TimelineProvider and selector hooks.",
      take: ["React"],
    },
    {
      path: "svelte",
      title: "Svelte",
      description: "Mount Lumen Timeline in Svelte 5 with the timeline attachment and selectors.",
      take: ["Svelte"],
    },
    {
      path: "solid",
      title: "SolidJS",
      description: "Mount Lumen Timeline in SolidJS 2 with createTimeline and signal selectors.",
      take: ["SolidJS"],
    },
    {
      path: "vue",
      title: "Vue",
      description:
        "Mount Lumen Timeline in Vue 3 with the Timeline component and shallowRef selectors.",
      take: ["Vue"],
    },
    {
      path: "verification",
      title: "Acceptance suite & benchmarks",
      description:
        "Lifecycle, steady playback, replay parity, bundle isolation, SSR checks and production benchmarks across all four wrappers.",
      take: ["Consumers and checks", "Benchmark"],
    },
  ];

  for (const [index, entry] of plan.entries()) {
    const parts = entry.take.map((title) => {
      const section = parsed.sections.find((item) => item.title === title);
      if (!section) throw new Error(`${source} has no "## ${title}" section`);
      used.add(title);
      return section;
    });
    const [first] = parts;
    let body = "";
    if (parts.length === 1 && first) {
      body = promoteHeadings(first.body);
    } else if (parts.length > 1) {
      body = joinSections(parts);
    }
    if (entry.intro) {
      body = body ? `${parsed.intro}\n\n${body}` : parsed.intro;
    }
    await writePage(
      `frameworks/${entry.path}.md`,
      { title: entry.title, description: entry.description, order: index + 1 },
      `${HTML_NOTE(source)}\n\n${body}`,
    );
  }

  // A section added to docs/frameworks.md has to be mapped to a page, never silently dropped.
  const missed = parsed.sections.filter((s) => !used.has(s.title)).map((s) => s.title);
  if (missed.length > 0) {
    throw new Error(`${source}: no page takes the section(s) ${missed.join(", ")}`);
  }
}

