// Builds packages/media/wasm/peaks.rs with Rust 1.100.0 and writes the module's
// bytes to packages/media/src/peaks-wasm.ts. With --check it rebuilds and fails
// when the committed bytes differ. Usage: node scripts/wasm.mjs [--check]
// Install the toolchain with:
//   rustup toolchain install 1.100.0 --profile minimal --target wasm32-unknown-unknown
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const source = "packages/media/wasm/peaks.rs";
const target = join(root, "packages/media/src/peaks-wasm.ts");
const toolchain = "1.100.0";
const dir = mkdtempSync(join(tmpdir(), "lumen-wasm-"));
try {
  const output = join(dir, "peaks.wasm");
  const rustc = (args) =>
    execFileSync("rustc", ["+" + toolchain, ...args], { cwd: root, encoding: "utf8" });
  const version = rustc(["--version"]).trim();
  rustc([
    "--edition=2024",
    "--target=wasm32-unknown-unknown",
    "--crate-type=cdylib",
    "-C",
    "opt-level=3",
    "-C",
    "codegen-units=1",
    "-C",
    "panic=abort",
    "-C",
    "strip=symbols",
    "-C",
    "target-feature=+simd128",
    "-C",
    "link-arg=--export=__heap_base",
    // Keep the build machine's paths out of the module.
    "--remap-path-prefix=" + root + "=",
    source,
    "-o",
    output,
  ]);
  const bytes = readFileSync(output);
  const sha256 = createHash("sha256").update(bytes).digest("hex");
  const text = `// Generated by scripts/wasm.mjs from ${source} with ${version}. Do not edit.
// Rebuild with \`npm run wasm:build\`; CI runs \`npm run wasm:check\`.

/** The peak kernels' WebAssembly module, base64. */
export const peaksWasm: string =
  "${bytes.toString("base64")}";

/** SHA-256 of the module's bytes. */
export const peaksWasmSha256: string =
  "${sha256}";
`;
  if (process.argv.includes("--check")) {
    const committed = readFileSync(target, "utf8");
    const found = /peaksWasmSha256: string =\s+"([0-9a-f]+)"/.exec(committed)?.[1];
    if (committed !== text) {
      console.error(
        `${target} differs from a fresh build with ${version}: committed ${found}, built ${sha256}.`,
      );
      process.exit(1);
    }
    console.log(`peaks-wasm.ts matches ${version} (${bytes.length} bytes, sha256 ${sha256}).`);
  } else {
    writeFileSync(target, text);
    console.log(`Wrote ${target}: ${bytes.length} bytes, sha256 ${sha256}, ${version}.`);
  }
} finally {
  rmSync(dir, { recursive: true, force: true });
}
